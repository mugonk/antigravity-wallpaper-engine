#!/usr/bin/env node
/**
 * Zero-dependency bundler for Antigravity Wallpaper Engine renderer modules.
 * Concatenates runtime/renderer/*.js in dependency order into runtime/renderer.bundle.js
 * and verifies syntax via Node's Function check / vm.Script.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const PARTS = [
  'state.js',
  'wallpaper-layer.js',
  'glass-engine.js',
  'fx-parallax.js',
  'ui-styles.js',
  'settings-modal.js',
  'ui-panel.js',
  'boot.js',
];

const chunks = [
  '/* Auto-generated by runtime/bundle-renderer.mjs — DO NOT EDIT DIRECTLY */\n',
  '(function () {\n"use strict";\n',
];

for (const name of PARTS) {
  const abs = join(__dirname, 'renderer', name);
  const src = readFileSync(abs, 'utf8');
  chunks.push(`\n/* ── ${name} ── */\n`);
  chunks.push(src);
  if (!src.endsWith('\n')) chunks.push('\n');
}

chunks.push('\n})();\n');

const bundle = chunks.join('');
// Validate JS syntax before writing
new vm.Script(bundle, { filename: 'renderer.bundle.js' });

const outPath = join(__dirname, 'renderer.bundle.js');
writeFileSync(outPath, bundle, 'utf8');
console.log(`[build] wrote ${outPath} (${Buffer.byteLength(bundle, 'utf8')} bytes, ${PARTS.length} modules)`);
